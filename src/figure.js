const choice = (id, label, group, sub, choices, def, hint) => ({
  id,
  label,
  group,
  sub,
  type: "choice",
  choices: choices.map(([value, l]) => ({ value, label: l })),
  default: def,
  hint,
});
const slider = (id, label, group, sub, min, max, step, unit, def, hint) => ({
  id,
  label,
  group,
  sub,
  type: "slider",
  min,
  max,
  step,
  unit,
  default: def,
  hint,
});
const toggle = (id, label, group, sub, def, hint) => ({
  id,
  label,
  group,
  sub,
  type: "toggle",
  default: def,
  hint,
});
// A size for one feature, 100% = as designed. `when` hides it if the feature is off.
const size = (id, label, group, sub, when = null, min = 50, max = 180) => ({
  ...slider(id, label, group, sub, min, max, 5, "%", 100),
  when,
});
